"""Builds the standalone LaTeX sources of the JSON vs TOON conversion figure (Study Design).

The text shown in the figure is taken from the study's own preprocessed test files, so it is
exactly what the LLM receives (minus the "Input Trace:" prefix). Lines are wrapped only at
attribute or field boundaries, and a check confirms that the wrapped text equals the original.
Two variants are written, one at the text width (figure*) and one at the column width (figure).
Usage: python make_format_conversion_figure.py   (then compile the two .tex files with pdflatex)
"""
import ast
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PRE = ROOT / "dataset" / "TraceBench" / "test" / "preprocessed"
OUT = Path(__file__).resolve().parent / "figures"   # .tex files are written next to this script
TRACE_ID = "QkPqbQ9p37dVdlizB32www=="   # trace shown in the figure
N_SHOWN = 2                              # spans/rows shown in each panel

HTTP = ("http.route", "http.status_code")   # attributes of the span with HTTP attributes (blue)
DB = ("db.operation", "db.sql.table", "db.name", "db.system")   # attributes of the database span (orange)
NL = ("\n", None)   # forced line break token


def load_input(fmt: str) -> str:
    data = json.load(open(PRE / f"test_tasks_preprocessed_{fmt}_with_step.json", encoding="utf-8"))
    hits = [x for x in data if TRACE_ID in x["input"]]
    assert hits, "trace not found"
    return hits[0]["input"].removeprefix("Input Trace: ")


def colour_of(key: str):
    return "B" if key in HTTP else "O" if key in DB else None


def wrap(tokens, width, cont):
    """Greedy wrap of (text, colour) tokens at token boundaries; returns the text with colour markers."""
    lines, cur = [], []          # cur: list of (text, colour)
    def length(parts): return len("".join(t for t, _ in parts).rstrip())
    for text, col in tokens:
        if (text, col) == NL:
            lines.append(cur); cur = []; continue
        if cur and length(cur) + len(text.rstrip()) > width:
            lines.append(cur); cur = [(" " * cont, None)]
        cur.append((text, col))
    lines.append(cur)
    out = []
    for parts in lines:
        # merge consecutive tokens of the same colour; strip trailing spaces of the line
        merged = []
        for t, c in parts:
            if merged and merged[-1][1] == c: merged[-1][0] += t
            else: merged.append([t, c])
        merged[-1][0] = merged[-1][0].rstrip()
        out.append("".join(f"<<{c}{t}{c}>>" if c else t for t, c in merged))
    return "\n".join(out)


def plain(s: str) -> str:
    return re.sub(r"\s+", "", re.sub(r"<<[BO]|[BO]>>", "", s))


def json_panel(raw: str, width: int) -> str:
    spans = ast.literal_eval(raw)
    n, toks = len(spans), []
    for si, sp in enumerate(spans[:N_SHOWN]):
        if si: toks.append(NL)
        items = list(sp.items())
        for i, (k, v) in enumerate(items):
            last = i == len(items) - 1
            text = f"{k!r}: {v!r}" + ("}, " if last else ", ")
            if i == 0: text = ("[{" if si == 0 else " {") + text
            toks.append((text, colour_of(k)))
    toks += [NL, (f"  ... {n - N_SHOWN} more spans ...]", None)]
    text = wrap(toks, width, 2)
    # fidelity check against the stored input
    want = "[" + ", ".join(repr(sp) for sp in spans[:N_SHOWN]) + f", ... {n - N_SHOWN} more spans ...]"  # whitespace-insensitive
    assert plain(text) == plain(want)
    assert all(repr(sp) in raw for sp in spans[:N_SHOWN])
    return text


def toon_panel(raw: str, width: int) -> str:
    lines = raw.split("\n")
    head, rows = lines[0], lines[1:]
    n = len(rows)
    pre, names = head.split("{", 1)
    names = names.rsplit("}:", 1)[0].split(",")
    toks = [(pre + "{", None)]
    for i, nm in enumerate(names):
        toks.append((nm + ("," if i < len(names) - 1 else "}:"), colour_of(nm)))
    for row in rows[:N_SHOWN]:
        vals = row.strip().split(",")
        assert len(vals) == len(names), "a value contains a comma"
        toks += [NL, ("  ", None)]
        first = True
        for i, (nm, v) in enumerate(zip(names, vals)):
            toks.append((v + ("," if i < len(vals) - 1 else ""), colour_of(nm)))
    toks += [NL, (f"  ... {n - N_SHOWN} more rows ...", None)]
    text = wrap(toks, width, 6)
    want = "\n".join([head] + [r for r in rows[:N_SHOWN]] + [f"... {n - N_SHOWN} more rows ..."])
    assert plain(text) == plain(want)
    return text


TEMPLATE = r"""% Conversion figure (Study Design): the same trace as JSON and as TOON.
% GENERATED by scripts/paper_figures/make_format_conversion_figure.py. Edit the script, not this file.
% Built at @WNAME@, so it is included at @INC@ with no scaling.
\documentclass[border={0pt 2pt 0pt 2pt}, varwidth=@W@]{standalone}
\usepackage{mathptmx}
\renewcommand{\ttdefault}{pcr}
\usepackage{xcolor}
\usepackage{textcomp}
\usepackage{listings}
\definecolor{bluecol}{RGB}{0,84,166}
\definecolor{orangecol}{RGB}{204,85,0}
\lstset{
  basicstyle=\ttfamily\scriptsize,
  columns=fullflexible,
  frame=single,
  rulecolor=\color{black!35},
  backgroundcolor=\color{black!2},
  upquote=true,
  framesep=3pt,
  xleftmargin=3.4pt,
  xrightmargin=3.4pt,
  aboveskip=2pt,
  belowskip=0pt,
  moredelim=[is][\color{bluecol}\bfseries]{<<B}{B>>},
  moredelim=[is][\color{orangecol}\bfseries]{<<O}{O>>}
}
\begin{document}
\noindent\textbf{\small (a) A trace in JSON (first two of seven spans)}

\vspace{2pt}
\begin{lstlisting}[]
@JSON@
\end{lstlisting}

\vspace{7pt}
\noindent\textbf{\small (b) The same trace in TOON (first two of seven rows)}

\vspace{2pt}
\begin{lstlisting}[]
@TOON@
\end{lstlisting}
\end{document}
"""

VARIANTS = {
    "format_conversion": dict(w="17.78cm", chars=112, wname="the text width of the ACM two-column format (7 in)", inc=r"\textwidth"),
    "format_conversion_col": dict(w="8.45cm", chars=52, wname="the column width of the ACM two-column format (3.33 in)", inc=r"\columnwidth"),
}

if __name__ == "__main__":
    rj, rt = load_input("JSON"), load_input("TOON")
    for name, kw in VARIANTS.items():
        text = (TEMPLATE.replace("@WNAME@", kw["wname"]).replace("@INC@", kw["inc"]).replace("@W@", kw["w"])
                .replace("@JSON@", json_panel(rj, kw["chars"])).replace("@TOON@", toon_panel(rt, kw["chars"])))
        OUT.mkdir(exist_ok=True)
        (OUT / f"{name}.tex").write_text(text, encoding="utf-8")
        print("wrote", OUT / f"{name}.tex")
